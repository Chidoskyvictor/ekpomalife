// Local check (dev DB): log in, then reopen the app in a new tab -> welcome back card.
import { chromium } from '@playwright/test'
import fs from 'node:fs'
const [account, out] = process.argv.slice(2)
const acct = JSON.parse(fs.readFileSync(account, 'utf8'))
const base = 'http://127.0.0.1:3005'
const browser = await chromium.launch({ channel: 'chrome' })
const ctx = await browser.newContext({ viewport: { width: 360, height: 740 }, isMobile: true, hasTouch: true })
const page = await ctx.newPage()
await page.goto(base + '/login', { timeout: 240000 })
await page.locator('input[autocomplete="username"]').waitFor({ timeout: 120000 })
await page.waitForTimeout(3000)
await page.locator('input[autocomplete="username"]').fill(acct.username)
await page.locator('input[type="password"]').fill(acct.password)
await page.getByRole('button', { name: /Enter Ekpoma/ }).click({ timeout: 60000 })
await page.waitForURL((u) => !u.pathname.startsWith('/login'), { timeout: 90000 })
await page.waitForTimeout(12000)
console.log('after login, card shown:', await page.getByRole('dialog', { name: 'Welcome back' }).isVisible().catch(() => false))
const again = await ctx.newPage()
await again.goto(base + '/', { timeout: 240000 })
await again.getByRole('dialog', { name: 'Welcome back' }).waitFor({ timeout: 90000 }).catch(() => {})
console.log('reopened, card shown:', await again.getByRole('dialog', { name: 'Welcome back' }).isVisible().catch(() => false))
await again.waitForTimeout(2500)
await again.screenshot({ path: `${out}/welcome.png` })
await again.getByRole('button', { name: 'Continue' }).click().catch(() => {})
await again.waitForTimeout(1000)
console.log('after Continue, card gone:', !(await again.getByRole('dialog', { name: 'Welcome back' }).isVisible().catch(() => false)))
await again.reload(); await again.waitForTimeout(15000)
console.log('reload same tab, card shown again:', await again.getByRole('dialog', { name: 'Welcome back' }).isVisible().catch(() => false))
await browser.close()
