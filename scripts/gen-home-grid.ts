/**
 * Builds the Buy-mode tile grid for each home from room-layouts.ts and writes it for both the
 * game (lib/game/home-grid.ts) and the API (backend/src/game/home-grid.ts), so they agree.
 * Run: npx tsx scripts/gen-home-grid.ts   (re-run whenever a home layout changes)
 */
import { copyFileSync, writeFileSync } from 'node:fs'
import { ROOM_LAYOUTS, type Rect } from '../lib/game/room-layouts'

const TILE = 0.6
/** The floors are where the character's centre may go, so the room itself reaches this much further. */
const WALL_GAP = 0.35
const BLOCK_GAP = 0.08

const HOMES = {
  'single-poultry': ROOM_LAYOUTS['single-room'],
  'selfcon-g2': ROOM_LAYOUTS.selfcon,
  'onebed-ojo': ROOM_LAYOUTS['one-bedroom'],
}

const inside = (x: number, z: number, [x0, z0, x1, z1]: Rect, gap: number) =>
  x >= x0 - gap && x <= x1 + gap && z >= z0 - gap && z <= z1 + gap
const hits = (a: Rect, [x0, z0, x1, z1]: Rect, gap: number) =>
  a[0] < x1 + gap && a[2] > x0 - gap && a[1] < z1 + gap && a[3] > z0 - gap
const r2 = (n: number) => Math.round(n * 100) / 100

const homes: Record<string, unknown> = {}
for (const [lodging, layout] of Object.entries(HOMES)) {
  const ox = Math.min(...layout.floors.map((f) => f[0])) - WALL_GAP
  const oz = Math.min(...layout.floors.map((f) => f[1])) - WALL_GAP
  const maxX = Math.max(...layout.floors.map((f) => f[2])) + WALL_GAP
  const maxZ = Math.max(...layout.floors.map((f) => f[3])) + WALL_GAP
  const cols = Math.floor((maxX - ox) / TILE)
  const rows = Math.floor((maxZ - oz) / TILE)
  const floor: string[] = []
  const blocked: string[] = []
  const startCol = Math.floor((layout.start[0] - ox) / TILE)
  const startRow = Math.floor((layout.start[1] - oz) / TILE)
  for (let r = 0; r < rows; r++) {
    let f = ''
    let b = ''
    for (let c = 0; c < cols; c++) {
      const rect: Rect = [ox + c * TILE, oz + r * TILE, ox + (c + 1) * TILE, oz + (r + 1) * TILE]
      const corners: [number, number][] = [
        [rect[0], rect[1]],
        [rect[2], rect[1]],
        [rect[0], rect[3]],
        [rect[2], rect[3]],
      ]
      const onFloor = corners.every(([x, z]) => layout.floors.some((fl) => inside(x, z, fl, WALL_GAP)))
      const taken = layout.blocks.some((bl) => hits(rect, bl, BLOCK_GAP))
      const door = Math.abs(c - startCol) <= 0 && Math.abs(r - startRow) <= 0
      f += onFloor ? '1' : '0'
      b += onFloor && (taken || door) ? '1' : '0'
    }
    floor.push(f)
    blocked.push(b)
  }
  homes[lodging] = { ox: r2(ox), oz: r2(oz), cols, rows, floor, blocked, start: [startCol, startRow] }
}

const header = '// Generated by scripts/gen-home-grid.ts from room-layouts.ts. Do not edit.\n'
const body = (suffix: string) =>
  header +
  `import type { HomeSpec } from './home-buy-rules${suffix}'\n\n` +
  `/** Metres per Buy-mode tile. */\nexport const HOME_TILE = ${TILE}\n\n` +
  `export const HOME_GRID: Record<string, HomeSpec> = ${JSON.stringify(homes, null, 1)}\n`
writeFileSync('lib/game/home-grid.ts', body(''))
writeFileSync('backend/src/game/home-grid.ts', body('.js'))
copyFileSync('lib/game/home-buy-rules.ts', 'backend/src/game/home-buy-rules.ts')
for (const [id, h] of Object.entries(homes) as [string, { floor: string[]; blocked: string[] }][]) {
  console.log(id)
  h.floor.forEach((row, i) => console.log(' ', [...row].map((ch, c) => (h.blocked[i][c] === '1' ? '#' : ch === '1' ? '.' : ' ')).join('')))
}
