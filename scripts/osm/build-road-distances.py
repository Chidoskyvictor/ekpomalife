"""
Real road distances between game places, from OpenStreetMap (OSRM routing over OSM roads).
The game map isn't to scale, so each place's real spot comes from an affine fit of its map u/v to
a few anchors picked on real Ekpoma roads (ANCHORS below). Distances are capped at 1.4x the straight
line so a place OSM can't reach directly (campus paths aren't mapped) doesn't get a long detour.

  python scripts/osm/build-road-distances.py  ->  backend/src/game/road-distances.ts
Map data (c) OpenStreetMap contributors, ODbL. Credited in the phone's Settings.
"""
import json, math, os, re, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PLACES = os.path.join(ROOT, "backend", "src", "game", "places.ts")
OUT = os.path.join(ROOT, "backend", "src", "game", "road-distances.ts")

# place id -> (lat, lon) on real Ekpoma roads
ANCHORS = {
    "aau-gate": (6.7470, 6.0930),  # AAU main campus gate, Ihumudumu
    "physical-science": (6.7560, 6.0880),  # north side of main campus
    "college-of-medicine": (6.7440, 6.1100),  # by G2 Road
    "market-square": (6.7410, 6.1390),  # town centre
    "spot-rite": (6.7385, 6.1290),  # town, off Ukpenu Road
    "sazza": (6.7470, 6.1000),  # off-campus, Efe Block Road side
}


def solve(A, b):
    n = len(A)
    M = [A[i][:] + [b[i]] for i in range(n)]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(M[r][c]))
        M[c], M[p] = M[p], M[c]
        for r in range(n):
            if r != c:
                f = M[r][c] / M[c][c]
                M[r] = [x - f * y for x, y in zip(M[r], M[c])]
    return [M[i][n] / M[i][i] for i in range(n)]


def main():
    src = open(PLACES, encoding="utf-8").read()
    uv = {k: (float(u), float(v)) for k, u, v in re.findall(r"'?([a-z0-9-]+)'?: \{ u: ([0-9.]+), v: ([0-9.]+) \}", src)}
    X = [[uv[k][0], uv[k][1], 1] for k in ANCHORS]
    Y = list(ANCHORS.values())

    def fit(j):
        AtA = [[sum(r[a] * r[b] for r in X) for b in range(3)] for a in range(3)]
        Atb = [sum(X[i][a] * Y[i][j] for i in range(len(X))) for a in range(3)]
        return solve(AtA, Atb)

    cl, cn = fit(0), fit(1)
    co = {k: (cl[0] * u + cl[1] * v + cl[2], cn[0] * u + cn[1] * v + cn[2]) for k, (u, v) in uv.items()}
    ids = list(co)
    coords = ";".join(f"{co[k][1]:.5f},{co[k][0]:.5f}" for k in ids)
    url = f"https://router.project-osrm.org/table/v1/driving/{coords}?annotations=distance"
    req = urllib.request.Request(url, headers={"User-Agent": "EkpomaLifeDev/1.0 (game build script)"})
    data = json.load(urllib.request.urlopen(req, timeout=60))
    assert data["code"] == "Ok", data

    def straight(a, b):
        (la, lo), (lb, lob) = co[a], co[b]
        return math.hypot((la - lb) * 111_000, (lo - lob) * 110_500)

    rows = []
    for i, a in enumerate(ids):
        row = []
        for j, b in enumerate(ids):
            road = data["distances"][i][j] or 0
            row.append(0 if a == b else round(min(road, straight(a, b) * 1.4) if road else straight(a, b) * 1.3))
        rows.append(row)

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("/*\n * Road distances in metres between game places (generated by scripts/osm/build-road-distances.py).\n")
        f.write(" * Map data (c) OpenStreetMap contributors (ODbL). Do not edit by hand.\n */\n\n")
        f.write(f"export const ROAD_IDS = {json.dumps(ids)} as const\n\n")
        f.write("const METRES: number[][] = [\n")
        for row in rows:
            f.write("  [" + ", ".join(str(x) for x in row) + "],\n")
        f.write("]\n\n")
        f.write("const INDEX = new Map<string, number>(ROAD_IDS.map((id, i) => [id, i]))\n\n")
        f.write("/** Road distance in km between two places, or null when either isn't on the table. */\n")
        f.write("export function roadKm(from: string, to: string): number | null {\n")
        f.write("  const a = INDEX.get(from)\n  const b = INDEX.get(to)\n")
        f.write("  if (a === undefined || b === undefined) return null\n")
        f.write("  return METRES[a]![b]! / 1000\n}\n")
    flat = sorted(x for r in rows for x in r if x)
    print("places", len(ids), "km min/median/max", flat[0] / 1000, flat[len(flat) // 2] / 1000, flat[-1] / 1000)


if __name__ == "__main__":
    main()
