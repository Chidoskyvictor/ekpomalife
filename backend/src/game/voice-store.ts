import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { AwsClient } from 'aws4fetch'
import { env } from '../env.js'

/*
 * Where voice note audio lives: a Cloudflare R2 bucket (S3 API) when R2_* is set, otherwise a local
 * folder in development so the feature works without a bucket. Production without R2 is switched off.
 */

const LOCAL_DIR = path.resolve(process.cwd(), '.voice-dev')

const r2 =
  env.R2_ACCOUNT_ID && env.R2_ACCESS_KEY_ID && env.R2_SECRET_ACCESS_KEY && env.R2_BUCKET
    ? {
        client: new AwsClient({
          accessKeyId: env.R2_ACCESS_KEY_ID,
          secretAccessKey: env.R2_SECRET_ACCESS_KEY,
          service: 's3',
          region: 'auto',
        }),
        base: `https://${env.R2_ACCOUNT_ID}.r2.cloudflarestorage.com/${env.R2_BUCKET}`,
      }
    : null

/** Voice notes can be sent: R2 is configured, or this is a development machine. */
export const voiceEnabled = (): boolean => Boolean(r2) || env.NODE_ENV !== 'production'

/** Keys are generated by us (`voice/<chat>/<id>.<ext>`), never taken from the client. */
const safeKey = (key: string) => /^voice\/[A-Za-z0-9_-]+\/[A-Za-z0-9_-]+\.[a-z0-9]+$/.test(key)

export async function putVoice(key: string, data: Buffer, contentType: string): Promise<void> {
  if (!safeKey(key)) throw new Error('bad voice key')
  if (r2) {
    const res = await r2.client.fetch(`${r2.base}/${key}`, {
      method: 'PUT',
      body: new Uint8Array(data),
      headers: { 'Content-Type': contentType },
    })
    if (!res.ok) throw new Error(`R2 upload failed: ${res.status}`)
    return
  }
  const file = path.join(LOCAL_DIR, key)
  await mkdir(path.dirname(file), { recursive: true })
  await writeFile(file, data)
}

/** The stored audio, or null when it is missing. */
export async function getVoice(key: string): Promise<Buffer | null> {
  if (!safeKey(key)) return null
  if (r2) {
    const res = await r2.client.fetch(`${r2.base}/${key}`)
    if (res.status === 404) return null
    if (!res.ok) throw new Error(`R2 download failed: ${res.status}`)
    return Buffer.from(await res.arrayBuffer())
  }
  try {
    return await readFile(path.join(LOCAL_DIR, key))
  } catch {
    return null
  }
}
